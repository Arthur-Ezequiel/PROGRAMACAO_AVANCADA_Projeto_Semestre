    private void carregarTabela() {

        List<ModelIngrediente> ingredientes
                = controllerIngrediente.listarTodos();

        javax.swing.table.DefaultTableModel modelo
                = new javax.swing.table.DefaultTableModel(
                        new Object[][]{},
                        new String[]{
                            "Código",
                            "Nome",
                            "Quantidade em Estoque"
                        }
                );

        for (ModelIngrediente ingrediente : ingredientes) {

            modelo.addRow(new Object[]{
                ingrediente.getCodIngrediente(),
                ingrediente.getNome(),
                ingrediente.getQuantidadeEstoque()
            });
        }

        TableLista.setModel(modelo);
    }

