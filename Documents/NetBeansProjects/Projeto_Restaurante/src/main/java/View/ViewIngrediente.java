    private void BtnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnCadastrarActionPerformed

        String nome = TextNome.getText();

        double quantidadeEstoque
                = Double.parseDouble(TextQuantidadeEstoque.getText());

        boolean sucesso = controllerIngrediente.cadastrar(
                nome,
                quantidadeEstoque
        );

        if (sucesso) {
            System.out.println("Ingrediente cadastrado com sucesso!");

            carregarTabela();

            TextCodigo.setText("");
            TextNome.setText("");
            TextQuantidadeEstoque.setText("");
        } else {
            System.out.println("Erro ao cadastrar ingrediente.");
        }
    }//GEN-LAST:event_BtnCadastrarActionPerformed

    private void BtnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnAlterarActionPerformed

        int codIngrediente
                = Integer.parseInt(TextCodigo.getText());

        String nome = TextNome.getText();

        double quantidadeEstoque
                = Double.parseDouble(TextQuantidadeEstoque.getText());

        boolean sucesso = controllerIngrediente.alterar(
                codIngrediente,
                nome,
                quantidadeEstoque
        );

        if (sucesso) {

            System.out.println("Ingrediente alterado com sucesso!");

            carregarTabela();

            TextCodigo.setText("");
            TextNome.setText("");
            TextQuantidadeEstoque.setText("");

        } else {

            System.out.println("Erro ao alterar ingrediente.");
        }
    }//GEN-LAST:event_BtnAlterarActionPerformed

    private void TableListaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TableListaMouseClicked

        int linha = TableLista.getSelectedRow();

        if (linha >= 0) {

            TextCodigo.setText(
                    TableLista.getValueAt(linha, 0).toString());

            TextNome.setText(
                    TableLista.getValueAt(linha, 1).toString());

            TextQuantidadeEstoque.setText(
                    TableLista.getValueAt(linha, 2).toString());
        }
    }//GEN-LAST:event_TableListaMouseClicked

    private void BtnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnBuscarActionPerformed

        int codIngrediente
                = Integer.parseInt(TextCodigo.getText());

        ModelIngrediente ingrediente
                = controllerIngrediente.buscarPorId(codIngrediente);

        if (ingrediente != null) {

            TextCodigo.setText(
                    String.valueOf(ingrediente.getCodIngrediente()));

            TextNome.setText(
                    ingrediente.getNome());

            TextQuantidadeEstoque.setText(
                    String.valueOf(ingrediente.getQuantidadeEstoque()));

        } else {

            System.out.println("Ingrediente não encontrado.");
        }
    }//GEN-LAST:event_BtnBuscarActionPerformed

