    private void carregarTabela() {

        List<ModelProduto> produtos = controllerProduto.listarTodos();

        DefaultTableModel modelo = new DefaultTableModel(
            new Object[]{"Código", "Nome", "Descrição", "Preço", "Em Estoque"}, 0
        );

        for (ModelProduto produto : produtos) {

            modelo.addRow(new Object[]{
                produto.getCodProduto(),
                produto.getNome(),
                produto.getDescricao(),
                produto.getPreco(),
                produto.isEmEstoque()
            });
        }

        TableLista.setModel(modelo);
    }


