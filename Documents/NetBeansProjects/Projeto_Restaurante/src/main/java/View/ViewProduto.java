    private void TableListaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TableListaMouseClicked
        int linha = TableLista.getSelectedRow();

        if (linha >= 0) {

            TextCodigo.setText(
                    TableLista.getValueAt(linha, 0).toString()
            );

            TextNome.setText(
                    TableLista.getValueAt(linha, 1).toString()
            );

            TextDescricao.setText(
                    TableLista.getValueAt(linha, 2).toString()
            );

            TextPreco.setText(
                    TableLista.getValueAt(linha, 3).toString()
            );

            CheckEmEstoque.setSelected(
                    Boolean.parseBoolean(
                            TableLista.getValueAt(linha, 4).toString()
                    )
            );
        }
    }//GEN-LAST:event_TableListaMouseClicked

    private void BtnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnCadastrarActionPerformed
        String nome = TextNome.getText();
        String descricao = TextDescricao.getText();
        double preco = Double.parseDouble(TextPreco.getText());
        boolean emEstoque = CheckEmEstoque.isSelected();

        boolean sucesso = controllerProduto.cadastrar(
                nome,
                descricao,
                preco,
                emEstoque
        );

        if (sucesso) {
            carregarTabela();

            TextCodigo.setText("");
            TextNome.setText("");
            TextDescricao.setText("");
            TextPreco.setText("");
            CheckEmEstoque.setSelected(false);
        }
    }//GEN-LAST:event_BtnCadastrarActionPerformed

    private void BtnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnAlterarActionPerformed
        int codProduto = Integer.parseInt(TextCodigo.getText());
        String nome = TextNome.getText();
        String descricao = TextDescricao.getText();
        double preco = Double.parseDouble(TextPreco.getText());
        boolean emEstoque = CheckEmEstoque.isSelected();

        boolean sucesso = controllerProduto.alterar(
                codProduto,
                nome,
                descricao,
                preco,
                emEstoque
        );

        if (sucesso) {
            carregarTabela();

            TextCodigo.setText("");
            TextNome.setText("");
            TextDescricao.setText("");
            TextPreco.setText("");
            CheckEmEstoque.setSelected(false);
        }
    }//GEN-LAST:event_BtnAlterarActionPerformed

    private void BtnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnExcluirActionPerformed
        int codProduto = Integer.parseInt(TextCodigo.getText());

        boolean sucesso = controllerProduto.excluir(codProduto);

        if (sucesso) {
            carregarTabela();

            TextCodigo.setText("");
            TextNome.setText("");
            TextDescricao.setText("");
            TextPreco.setText("");
            CheckEmEstoque.setSelected(false);
        }
    }//GEN-LAST:event_BtnExcluirActionPerformed

    private void BtnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnBuscarActionPerformed
        int codProduto = Integer.parseInt(TextCodigo.getText());

        ModelProduto produto = controllerProduto.buscarPorId(codProduto);

        if (produto != null) {

            TextCodigo.setText(String.valueOf(produto.getCodProduto()));
            TextNome.setText(produto.getNome());
            TextDescricao.setText(produto.getDescricao());
            TextPreco.setText(String.valueOf(produto.getPreco()));
            CheckEmEstoque.setSelected(produto.isEmEstoque());
        }
    }//GEN-LAST:event_BtnBuscarActionPerformed

