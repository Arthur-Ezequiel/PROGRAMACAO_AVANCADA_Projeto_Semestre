    private void BtnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnCadastrarActionPerformed
        String nome = TextNome.getText();
        String contato = TextContato.getText();
        String observacao = TextObservacao.getText();

        if (nome.isEmpty()) {
            return;
        }

        boolean sucesso = controllerCliente.cadastrar(
                nome,
                contato,
                observacao
        );

        if (sucesso) {
            limparCampos();
            carregarTabela();
        }
    }//GEN-LAST:event_BtnCadastrarActionPerformed

    private void TableListaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TableListaMouseClicked
        int linha = TableLista.getSelectedRow();

        if (linha == -1) {
            return;
        }

        TextCodigo.setText(
                TableLista.getValueAt(linha, 0).toString()
        );

        TextNome.setText(
                TableLista.getValueAt(linha, 1).toString()
        );

        TextContato.setText(
                TableLista.getValueAt(linha, 2).toString()
        );

        Object observacao = TableLista.getValueAt(linha, 3);

        if (observacao != null) {
            TextObservacao.setText(observacao.toString());
        } else {
            TextObservacao.setText("");
        }
    }//GEN-LAST:event_TableListaMouseClicked

    private void BtnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnAlterarActionPerformed
        if (TextCodigo.getText().isEmpty()) {
            return;
        }

        int codCliente;

        try {
            codCliente = Integer.parseInt(TextCodigo.getText());
        } catch (NumberFormatException e) {
            return;
        }

        String nome = TextNome.getText();
        String contato = TextContato.getText();
        String observacao = TextObservacao.getText();

        if (nome.isEmpty()) {
            return;
        }

        boolean sucesso = controllerCliente.alterar(
                codCliente,
                nome,
                contato,
                observacao
        );

        if (sucesso) {
            limparCampos();
            carregarTabela();
        }
    }//GEN-LAST:event_BtnAlterarActionPerformed

    private void BtnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnBuscarActionPerformed
        int codCliente = Integer.parseInt(TextCodigo.getText());

        ModelCliente cliente = controllerCliente.buscarPorId(codCliente);

        if (cliente != null) {

            TextCodigo.setText(String.valueOf(cliente.getCodCliente()));
            TextNome.setText(cliente.getNome());
            TextContato.setText(cliente.getContato());
            TextObservacao.setText(cliente.getObservacao());
        }
    }//GEN-LAST:event_BtnBuscarActionPerformed

